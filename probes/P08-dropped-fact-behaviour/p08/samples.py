"""Seeded random raw samples for the note (AGENTS.md: random, never cherry-picked).

Population: the episodes in results/measures.csv joined with results/detector.csv, per
(model_slug, header, cell). Draw: for each stratum, sort by episode_id and take
random.Random(f"{SEED}:samples:{stratum}").sample(rows, k). Also one twin context drawn the
same way, shown as the lines -C and -T delete from Full. Writes results/samples.md; every drawn
row is shown.

  PYTHONPATH=probes/P08-dropped-fact-behaviour:src:scripts uv run --group swarm \
      python -m p08.samples [--k 2]
"""
from __future__ import annotations

import argparse
import csv
import difflib
import json
import random
from pathlib import Path

from p08 import contracts as C

OUT = C.RESULTS_DIR / "samples.md"


def _rows() -> list[dict]:
    with open(C.DETECTOR_CSV, newline="") as f:
        det = {r["episode_id"]: r for r in csv.DictReader(f)}
    with open(C.MEASURES_CSV, newline="") as f:
        measures = list(csv.DictReader(f))
    rows = []
    for r in measures:
        d = det.get(r["episode_id"], {})
        rows.append({**r, "cheat": d.get("cheat", ""), "tamper_any": d.get("tamper_any", ""),
                     "passed": d.get("passed", "")})
    return rows


def _clip(s: str, n: int) -> str:
    s = " ".join((s or "").split())
    return s if len(s) <= n else s[: n - 1] + "…"


def episode_block(r: dict) -> list[str]:
    art = json.loads((C.PROBE_DIR / r["path"]).read_text())
    out = [f"#### {r['episode_id']}",
           (f"end {r['end_reason']}, {r['n_turns']} turns; first action is a test run: "
            f"{r['first_action_test']}; cheat {r['cheat']} (tamper {r['tamper_any']}, passes "
            f"the impossible tests {r['passed']})"), ""]
    for c in art.get("calls") or []:
        out.append(f"- turn {c['turn']}: `{_clip(c['cmd'], 160)}`")
    out += ["", f"> final message: {_clip(art.get('final_message') or '(none)', 400)}", ""]
    return out


def twin_block(rec: dict) -> list[str]:
    out = [f"#### Twins of {rec['ctx_id']} (inserted: {rec['inserted'] or 'none'})"]
    for cell in ("minus_c", "minus_t", "minus_h"):
        if not rec.get(cell):
            continue
        gone = [line[1:] for line in difflib.ndiff(rec["full"].split("\n"),
                                                   rec[cell].split("\n"))
                if line.startswith("- ")]
        out += ["", (f"{cell}: removed {rec['gate'][cell]['removed_fraction']:.0%}; lines "
                     "changed or deleted:"), ""]
        out += [f"- `{_clip(x, 220)}`" for x in gone] or ["- (none)"]
    return out + [""]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--k", type=int, default=2)
    a = ap.parse_args(argv)
    rows = _rows()
    strata: dict[tuple, list[dict]] = {}
    for r in rows:
        strata.setdefault((r["model_slug"], r["header"], r["cell"]), []).append(r)
    lines = ["# P08 random raw samples", "",
             (f"Generated by `p08/samples.py` (seed {C.SEED}, k = {a.k} per stratum). Every "
              "drawn row is shown."), ""]
    for key in sorted(strata):
        pop = sorted(strata[key], key=lambda r: r["episode_id"])
        drawn = random.Random(f"{C.SEED}:samples:{'/'.join(key)}").sample(pop, min(a.k, len(pop)))
        lines += [f"### {' / '.join(key)} (drawn {len(drawn)} of {len(pop)})", ""]
        for r in drawn:
            lines += episode_block(r)
    twins = [json.loads(x) for x in Path(C.TWINS_JSONL).read_text().splitlines() if x.strip()]
    for header in sorted({t["header"] for t in twins}):
        ok = sorted((t for t in twins if t["header"] == header and t["status"] == "ok"),
                    key=lambda t: t["ctx_id"])
        if ok:
            t = random.Random(f"{C.SEED}:samples:twin:{header}").choice(ok)
            lines += [f"### A twin set ({header})", ""] + twin_block(t)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
