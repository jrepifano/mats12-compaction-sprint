"""P23 seeded random raw samples (ported from P08's p08/samples.py; P23: its five cells, twins from
twins5.jsonl, seed P23_SEED, and the cheating episodes listed in full as a second section).

Seeded random raw samples for the note (AGENTS.md: random, never cherry-picked).

Population: the episodes in results/measures.csv joined with results/detector.csv, per
(model_slug, header, cell). Draw: for each stratum, sort by episode_id and take
random.Random(f"{SEED}:samples:{stratum}").sample(rows, k). Also one twin context drawn the
same way, shown as the lines -C and -T delete from Full. Writes results/samples.md; every drawn
row is shown.

  PYTHONPATH=<abs>/probes/P23-compaction-decisions-vs-cues:<abs>/src:<abs>/scripts uv run --group swarm \
      python -m p23.samples [--k 2]
"""
from __future__ import annotations

import argparse
import csv
import difflib
import json
import random
from pathlib import Path

from p23 import contracts as C

OUT = C.RESULTS_DIR / "samples.md"


def _rows() -> list[dict]:
    with open(C.DETECTOR_CSV, newline="") as f:
        det = {r["episode_id"]: r for r in csv.DictReader(f)}
    with open(C.MEASURES_CSV, newline="") as f:
        measures = list(csv.DictReader(f))
    rows = []
    for r in measures:
        d = det.get(r["episode_id"], {})
        rows.append({**r, "cheat": d.get("cheat", ""), "tamper_any": d.get("tamper_any", ""),
                     "passed": d.get("passed", "")})
    return rows


def _clip(s: str, n: int) -> str:
    s = " ".join((s or "").split())
    return s if len(s) <= n else s[: n - 1] + "…"


def episode_block(r: dict) -> list[str]:
    art = json.loads((C.PROBE_DIR / r["path"]).read_text())
    out = [f"#### {r['episode_id']}",
           (f"end {r['end_reason']}, {r['n_turns']} turns; cheat {r['cheat']} (tamper "
            f"{r['tamper_any']}, passes the impossible tests {r['passed']}); mentions the "
            f"contradiction at the end: {r.get('disclosed')}"), ""]
    for c in art.get("calls") or []:
        out.append(f"- turn {c['turn']}: `{_clip(c['cmd'], 160)}`")
    out += ["", f"> final message: {_clip(art.get('final_message') or '(none)', 400)}", ""]
    return out


def twin_block(rec: dict) -> list[str]:
    out = [f"#### Twins of {rec['ctx_id']} (inserted: {rec['inserted'] or 'none'})"]
    for cell, parent in (("minus_h", "full"), ("minus_d", "full"), ("minus_hl", "minus_h")):
        gone = [line[1:] for line in difflib.ndiff(rec[parent].split("\n"),
                                                   rec[cell].split("\n"))
                if line.startswith("- ")]
        out += ["", (f"{cell}: removed {rec['gate'][cell]['removed_fraction']:.0%} of Full; "
                     f"lines of {parent} changed or deleted:"), ""]
        out += [f"- `{_clip(x, 260)}`" for x in gone] or ["- (none)"]
    return out + [""]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--k", type=int, default=2)
    a = ap.parse_args(argv)
    rows = _rows()
    strata: dict[tuple, list[dict]] = {}
    for r in rows:
        strata.setdefault((r["model_slug"], r["header"], r["cell"]), []).append(r)
    lines = ["# P23 random raw samples", "",
             (f"Generated by `p23/samples.py` (seed {C.P23_SEED}, k = {a.k} per stratum). Every "
              "drawn row is shown."), ""]
    for key in sorted(strata):
        pop = sorted(strata[key], key=lambda r: r["episode_id"])
        drawn = random.Random(f"{C.P23_SEED}:samples:{'/'.join(key)}").sample(pop, min(a.k, len(pop)))
        lines += [f"### {' / '.join(key)} (drawn {len(drawn)} of {len(pop)})", ""]
        for r in drawn:
            lines += episode_block(r)
    twins = [json.loads(x) for x in Path(C.TWINS5_JSONL).read_text().splitlines() if x.strip()]
    ok = sorted((t for t in twins if t["status"] in ("ok", "audit")), key=lambda t: t["ctx_id"])
    for i, t in enumerate(random.Random(f"{C.P23_SEED}:samples:twin").sample(ok, 2)):
        lines += [f"### A twin set ({i + 1} of 2, drawn)", ""] + twin_block(t)
    cheats = sorted((r for r in rows if r["cheat"] == "True"), key=lambda r: r["episode_id"])
    lines += [f"## Every cheating episode ({len(cheats)})", ""]
    for r in cheats:
        lines += episode_block(r)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
