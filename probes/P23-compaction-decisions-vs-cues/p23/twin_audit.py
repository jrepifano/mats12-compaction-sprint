"""P23 twin audit sheet (plan.md "Setup": the session reads the diffs of all four deletion twins
for every context). Free. Writes results/twin_audit.md: per context, what -H, -D and -H-L
removed (word-level diff against their parent), the leak checker's second-round listing, and
sentences left in -D that hold a decision keyword (a prompt for the reader, not a verdict).
The session's verdicts go in data/audit.json ({ctx_id: {"pass": bool, "note": str}}).

  PYTHONPATH=probes/P23-compaction-decisions-vs-cues:src:scripts uv run python -m p23.twin_audit
"""
from __future__ import annotations

import difflib
import json
import re

from p23 import contracts as C

_WORD = re.compile(r"\S+")
KEYWORDS = re.compile(r"\b(?:hack\w*|gam(?:e|ing)\b|honest\w*|special[- ]?cas\w*|cheat\w*|"
                      r"stateful|call[- ]count\w*|document\w*|report\w*|despite|rather than|"
                      r"instead|accept\w*|ignor\w*|chose|choos\w*|decid\w*|reject\w*|"
                      r"refus\w*|correctness over|faithful|in favor of|in favour of)\b",
                      re.IGNORECASE)


def removed(parent: str, child: str) -> list[str]:
    """Runs of words in `parent` that `child` lacks (word-level diff)."""
    a, b = _WORD.findall(parent), _WORD.findall(child)
    sm = difflib.SequenceMatcher(a=a, b=b, autojunk=False)
    return [" ".join(a[i1:i2]) for op, i1, i2, _, _ in sm.get_opcodes()
            if op in ("delete", "replace")]


def remnants(text: str) -> list[str]:
    out = []
    for line in text.split("\n"):
        for snt in re.split(r"(?<=[.;])\s+", line):
            if KEYWORDS.search(snt):
                out.append(snt.strip()[:220])
    return out


def main() -> int:
    recs = [json.loads(x) for x in C.TWINS5_JSONL.read_text().splitlines() if x.strip()]
    lines = ["# P23 twin audit sheet", "",
             ("Generated by `p23/twin_audit.py` from `data/twins5.jsonl`. For each context: "
              "what each deletion twin removed from its parent, the leak checker's round-2 "
              "listing, and keyword sentences left in -D."), ""]
    for r in recs:
        if r["status"] not in ("ok", "audit"):
            continue
        lines += [(f"## {r['ctx_id']} ({r['status']}, {len(r['spans'])} spans, "
                   f"-D removes {r['gate']['minus_d']['removed_fraction']:.1%})"), ""]
        for name, parent in (("minus_d", "full"), ("minus_h", "full"),
                             ("minus_hd", "minus_h"), ("minus_hl", "minus_h")):
            lines.append(f"- **{name}** removed: " + " ‖ ".join(
                f"`{x[:200]}`" for x in removed(r[parent], r[name])))
        if len(r["leaks"]) == 2:
            lines.append(f"- leak round 2 lists: {r['leaks'][1].get('listed')}")
        rem = remnants(r["minus_d"])
        lines.append("- keyword sentences left in -D: " + (" ‖ ".join(rem) if rem else "none"))
        rem = remnants(r["minus_hd"])
        lines.append("- keyword sentences left in -H-D: " + (" ‖ ".join(rem) if rem else "none"))
        lines.append("")
    out = C.RESULTS_DIR / "twin_audit.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
