# --- wrappers on a real stitched history -------------------------------------------------------
def test_inspect_on_history(h0):
    res, summ = run("inspect", h0.messages, h0.tools)
    assert res.error is None and len(summ.calls) == 1
    call = summ.calls[0]
    assert call["tools"] is None and call["max_tokens"] == C.SUMMARY_MAX_TOKENS["inspect"]
    req = call["messages"]
    assert req[:-1] == h0.messages                       # trigger: the whole history, at its end
    assert req[-1] == {"role": "user", "content":
                       compact.prompt("inspect_summary_prompt.txt").format(addendums="")}
    assert res.summary_text == "<summary>\n1. Primary Request: fix it\n</summary>"
    assert res.carry_over == [h0.messages[0], h0.messages[1],
                              {"role": "user", "content": compact.inspect_wrap(res.summary_text)}]
    assert res.prompt_sha256 == compact.prompt_sha256("inspect")
    assert res.request_sha256 == compact.request_sha256(
        [C.make_body(req, None, C.SUMMARY_MAX_TOKENS["inspect"])])
    assert res.input_tokens == tokens.count(req, None) == call["our_tokens"]
    assert res.carry_tokens == tokens.count(res.carry_over, h0.tools)
    assert res.cost_usd == 0.01 and res.summary_tokens == 50
    assert res.truncation["fit_passes"] == []


def test_inspect_size_arm_and_chain_k1_to_k3(h0):
    s1 = stitch.size_arm_messages(h0)
    r120, _ = run("inspect", s1, h0.tools, source="S1")
    assert r120.carry_over[:2] == h0.messages[:2] and r120.source == "S1"
    used = set(h0.instances)
    res1, _ = run("inspect", h0.messages, h0.tools)
    ctx = res1.carry_over
    for k in (2, 3):
        ctx_k, info = replay.extend(ctx, h0.tools, history=h0, k=k, used_instances=used,
                                    seed=h0.seed)
        assert ctx_k[:3] == ctx and ctx_k[2]["content"].startswith("[CONTEXT COMPACTION SUMMARY]")
        assert C.BAND[0] <= info["tokens"] * C.CALIB.c <= C.BAND[1]
        summ = MockSummarizer(text=f"<summary>summary {k}</summary>")
        res_k, summ = run("inspect", ctx_k, h0.tools, summ, k=k, source=f"rep{k}")
        req = summ.calls[0]["messages"]
        assert req[:-1] == ctx_k                         # summary of summary + fill block
        assert req[1] == h0.messages[1]                  # S1's task input at every k
        assert res_k.kept["previous_summary"] is True
        assert res_k.carry_over[1] == h0.messages[1]
        assert res_k.carry_over[2]["content"] == compact.inspect_wrap(f"<summary>summary {k}</summary>")
        ctx = res_k.carry_over
    assert used > set(h0.instances)                       # F1 and F2 instances added


def test_codex_on_history(h0):
    res, summ = run("codex", h0.messages, h0.tools, MockSummarizer(text="SUM"))
    req = summ.calls[0]["messages"]
    assert summ.calls[0]["tools"] is None
    assert req[0] == h0.messages[0] and req[-1]["content"] == compact.prompt("codex_prompt.md")
    assert len(req) == len(h0.messages) + 1
    co = res.carry_over
    assert co[0] == h0.messages[0]
    assert co[-1] == {"role": "user", "content": compact.prompt("codex_summary_prefix.md") + "\nSUM"}
    users = [m for m in h0.messages if m["role"] == "user"]
    assert co[1:-1] == users                             # every user message fits in 20k
    assert h0.messages[1] in co and h0.messages[h0.join_index] in co   # S1's and S2's tasks
    assert res.kept["s1_task_verbatim"] and res.kept["join_tasks_verbatim"] == [h0.join_index]
    assert all(m["role"] == "user" for m in co[1:])


