import pytest
from p49 import compact, replay, stitch, tokens
from p49 import contracts as C

SUMMARY = "<analysis>\nthinking\n</analysis>\n\n<summary>\n1. Primary Request: fix it\n</summary>"


class MockSummarizer:
    def __init__(self, text=SUMMARY, finish="stop"):
        self.text, self.finish, self.calls = text, finish, []

    async def __call__(self, messages, max_tokens, tools, our_tokens):
        self.calls.append({"messages": messages, "max_tokens": max_tokens, "tools": tools,
                           "our_tokens": our_tokens})
        return C.Response(message={"role": "assistant", "content": self.text},
                          finish_reason=self.finish, prompt_tokens=None, completion_tokens=50,
                          cost_usd=0.01, cost_from_usage=True, provider="mock", latency_s=0.0,
                          attempts=1, gen_id=None)


def run(method, messages, tools, summ=None, **kw):
    summ = summ or MockSummarizer()
    res = asyncio.run(compact.build(method, messages, tools, summ, history_id="h0", **kw))
    return res, summ


@pytest.fixture(scope="module")
def h0():
    if not C.INDEX_JSON.exists():
        pytest.skip("no length index")
    if stitch.history_path("h0").exists():
        return stitch.load_history("h0")
    return stitch.build_history(0)


def _file_sha(name):
    return hashlib.sha256((C.PROMPTS_DIR / name).read_bytes()).hexdigest()


# --- prompts ----------------------------------------------------------------------------------
def test_sources_md_lists_every_prompt_with_its_sha():
    src = (C.PROMPTS_DIR / "SOURCES.md").read_text()
    for files in compact.PROMPT_FILES.values():
        for name in files:
            assert name in src and _file_sha(name) in src, name


