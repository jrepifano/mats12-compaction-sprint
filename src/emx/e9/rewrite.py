"""E9 rewriter (implementation plan v4, unit B2a): corrections (prompt A.2) and stance-preserving
paraphrases (prompt A.3) of the insert documents, with the writer routing and the bounded
regeneration sequence of prereg §4.4 "Writers and the regeneration sequence" (Amendment B):

1. gpt-6-luna (`ROLES["writer"]`) writes each document version with `REWRITE_REQUEST_SEED`
   (attempt 1);
2. if luna refuses or returns nothing (llm status "refused", which includes content filters, or
   "empty"), the Qwen fallback (`ROLES["fallback_writer"]`) writes it with the same prompt and
   seed (attempt 1, writer "qwn");
3. if the attempt-1 output fails its checks (decided by unit B2b, `emx.e9.checks`), the same
   writer regenerates it once with `REWRITE_REQUEST_SEED + 1` (attempt 2). A Qwen refusal at
   step 2 counts as that output failing and is regenerated by Qwen;
4. a regeneration that still fails, or is refused or empty, drops the document (B2b replaces it).

API errors. `llm.run_batch` treats "error" as non-terminal (an API failure after its retries, or a
request cut off by the reservation's headroom or a fatal error) and re-sends it on the next run.
An error is not an answer from the writer, so by default it is NOT recorded as an attempt: the
item stays "pending" and the next call re-sends it to the same writer. Only with
`errors_to_fallback=True` (for an item that keeps failing across reruns) is an error row that was
actually sent (`attempts > 0`) recorded as a failed attempt, which routes it like a refusal.

Every attempt is appended to `data/E9/rewrite/attempts.jsonl` (`contracts.REWRITE_ATTEMPT_KEYS`
plus provenance), keyed by (doc_id, version, attempt, writer); a key already recorded is never
re-sent, so every call here is resumable. The LLM layer (`emx.e9.llm.run_batch`, unit B1) is
itself resumable and owns reservations and settlement; it is imported lazily and injectable for
tests. Reported per §4.4: the refusal rate at each step, the regeneration outcomes, the number of
Qwen-written outputs, and the endorsement scores of refused documents against the rest.

Binding to inputs (code review R1, finding 4). Every attempt stores a `fingerprint`: the sha256
of its document text, prompt id and prompt-file sha256, the writer's model id, route, request
config and max tokens, and the seed. Before any call (and in the dry-run projections), every
recorded attempt that would be reused for a requested (doc, version) is re-fingerprinted against
the current inputs; a mismatch raises `FingerprintMismatch` before anything is sent. A returned
LLM row whose prompt sha, model or seed differs from the request is refused, not recorded.

Explicit outcomes (finding 1). `write_versions` and `regenerate` return an entry for EVERY
requested (doc, version): an attempt record, or `{"doc_id", "version", "status": "unresolved",
"reason"}` when an API error or a headroom cut-off left it without a terminal answer. Unresolved
is resumable work (call again), never evidence that a check failed.

Exclusions. Documents in the shared exclusion registry (`emx.e9.checks.load_exclusions()`,
`data/E9/insert/exclusions.json`, e.g. §4.3's minor-safety flag raised later by the checker) are
never sent: both entry points raise `ExcludedDocument` before any call.

Prompt ids: "A2_correct" (corr), "A3_paraphrase" (para). Item ids: "{doc_id}|{version}|{attempt}".
Ledger notes: `contracts.ledger_note(stage, "rewrite", f"{model}-{version}-a{attempt}-{batch}")`,
one per run_batch call; `stage` is "setup" in Part 1 and "part2_mandatory" for the confirmation
corrections (unit H).
"""

from __future__ import annotations

import json
import statistics
from collections import Counter
from collections.abc import Callable, Iterable, Mapping
from datetime import UTC, datetime
from pathlib import Path

from emx.e9 import contracts as C
from emx.e9 import text as T

REPO_ROOT = Path(__file__).resolve().parents[3]
REWRITTEN: tuple[str, ...] = ("corr", "para")
PROMPT_FOR: dict[str, str] = {"corr": "A2_correct", "para": "A3_paraphrase"}
LUNA: str = C.ROLES["writer"]  # type: ignore[assignment]
QWN: str = C.ROLES["fallback_writer"]  # type: ignore[assignment]
# Recorded statuses that send luna's attempt 1 to the fallback ("nothing usable"). §4.4 names
# refusals and empty answers; "malformed" cannot occur in text mode; "error" is recorded only
# under errors_to_fallback (module docstring).
FALLBACK_STATUSES: tuple[str, ...] = ("refused", "empty", "error", "malformed")
UNRESOLVED = "unresolved"
ATTEMPTS_FILE = "attempts.jsonl"
STEP = "rewrite"

Key = tuple[str, str, int, str]  # (doc_id, version, attempt, writer)
DV = tuple[str, str]  # (doc_id, version)


class FingerprintMismatch(ValueError):
    """A recorded attempt does not match the current document text, prompt, model or seed."""


class ExcludedDocument(ValueError):
    """A document in the shared exclusion registry was submitted for rewriting."""


# --- paths and records ----------------------------------------------------------------------------


def _root_path(p: str | Path) -> Path:
    p = Path(p)
    return p if p.is_absolute() else REPO_ROOT / p


def attempts_path(out_dir: str | Path = C.REWRITE_DIR) -> Path:
    return _root_path(out_dir) / ATTEMPTS_FILE


def _key(rec: Mapping) -> Key:
    return (rec["doc_id"], rec["version"], int(rec["attempt"]), rec["writer"])


def load_attempts(out_dir: str | Path = C.REWRITE_DIR) -> dict[Key, dict]:
    """Every recorded attempt, keyed by (doc_id, version, attempt, writer); last line wins."""
    path = attempts_path(out_dir)
    out: dict[Key, dict] = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if line.strip():
                rec = json.loads(line)
                out[_key(rec)] = rec
    return out


def _append(out_dir: str | Path, recs: list[dict]) -> None:
    if not recs:
        return
    path = attempts_path(out_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as f:
        f.write("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in recs))
        f.flush()


def _by_dv(attempts: Mapping[Key, dict]) -> dict[DV, dict[tuple[int, str], dict]]:
    out: dict[DV, dict[tuple[int, str], dict]] = {}
    for (doc_id, version, attempt, writer), rec in attempts.items():
        out.setdefault((doc_id, version), {})[(attempt, writer)] = rec
    return out


def _attempt1_writer(recs: Mapping[tuple[int, str], dict]) -> str | None:
    """The writer whose attempt 1 stands: Qwen once it has written, else luna (§4.4 steps 1-2)."""
    if (1, QWN) in recs:
        return QWN
    if (1, LUNA) in recs:
        return LUNA
    return None


def _current(recs: Mapping[tuple[int, str], dict]) -> dict | None:
    a2 = [r for (a, _), r in recs.items() if a == 2]
    if a2:
        return a2[0]
    w = _attempt1_writer(recs)
    return recs[(1, w)] if w else None


def current_version(
    doc_id: str,
    version: str,
    *,
    attempts: Mapping[Key, dict] | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
) -> dict | None:
    """The attempt that now stands for (doc_id, version): the regeneration if one exists, else
    Qwen's attempt 1 if Qwen wrote, else luna's attempt 1; None if nothing was written. The
    record may be a refusal: check `rec["status"] == "ok"` (or use `version_state`)."""
    attempts = load_attempts(out_dir) if attempts is None else attempts
    return _current(_by_dv(attempts).get((doc_id, version), {}))


def version_state(
    doc_id: str,
    version: str,
    *,
    attempts: Mapping[Key, dict] | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
) -> str:
    """Where (doc_id, version) is in the §4.4 sequence:
    "pending" (nothing written), "needs_fallback" (luna refused/empty, Qwen not yet called),
    "to_check" (an ok attempt-1 output awaiting B2b's checks), "refused_fallback" (Qwen refused
    too: counts as failing, goes to `regenerate`), "regenerated" (an ok attempt-2 output awaiting
    its checks), "dropped" (the regeneration was refused or empty)."""
    attempts = load_attempts(out_dir) if attempts is None else attempts
    recs = _by_dv(attempts).get((doc_id, version), {})
    cur = _current(recs)
    if cur is None:
        return "pending"
    ok = cur["status"] == "ok"
    if cur["attempt"] == 2:
        return "regenerated" if ok else "dropped"
    if ok:
        return "to_check"
    return "refused_fallback" if cur["writer"] == QWN else "needs_fallback"


def state_counts(
    doc_ids: Iterable[str],
    versions: Iterable[str] = REWRITTEN,
    *,
    attempts: Mapping[Key, dict] | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
) -> dict[str, int]:
    """How many (doc, version) pairs are in each `version_state`."""
    attempts = load_attempts(out_dir) if attempts is None else attempts
    return dict(Counter(version_state(d, v, attempts=attempts) for d in doc_ids for v in versions))


def refused_fallbacks(
    *, attempts: Mapping[Key, dict] | None = None, out_dir: str | Path = C.REWRITE_DIR
) -> list[tuple[str, str, str]]:
    """(doc_id, version, "qwn") for every Qwen attempt-1 refusal not yet regenerated. These go to
    `regenerate` with B2b's check failures (§4.4 step 3: a refusal at step 2 counts as failing)."""
    attempts = load_attempts(out_dir) if attempts is None else attempts
    return sorted(
        (d, v, QWN)
        for (d, v) in _by_dv(attempts)
        if version_state(d, v, attempts=attempts) == "refused_fallback"
    )


# --- the LLM calls --------------------------------------------------------------------------------


def _run_batch_default() -> Callable:
    from emx.e9 import llm  # lazy: written by unit B1

    return llm.run_batch


def _estimate_default() -> Callable:
    from emx.e9 import llm

    return llm.estimate_usd


def _prompt_sha(prompt_id: str) -> str:
    from emx.e9 import prompts  # lazy: written by unit B1

    return prompts.sha256(prompt_id)


def _seed(attempt: int) -> int:
    return C.REWRITE_REQUEST_SEED + (attempt - 1)


def fingerprint(doc_text: str, version: str, writer: str, attempt: int) -> str:
    """sha256 over everything that determines an attempt's request (module docstring)."""
    spec = C.MODELS[writer]
    payload = {
        "orig_sha256": T.text_sha256(doc_text),
        "prompt_id": PROMPT_FOR[version],
        "prompt_sha256": _prompt_sha(PROMPT_FOR[version]),
        "model": spec.model,
        "route": spec.route,
        "request": spec.request,
        "max_tokens": spec.text_max_tokens,
        "mode": "text",
        "seed": _seed(attempt),
    }
    return T.text_sha256(json.dumps(payload, sort_keys=True))


def excluded_ids() -> set[str]:
    """Doc ids in the shared exclusion registry (fails closed if it cannot be loaded)."""
    try:
        from emx.e9.checks import load_exclusions  # lazy: written by unit B2b
    except (ImportError, AttributeError) as e:  # fail closed: never rewrite unchecked
        raise RuntimeError(f"cannot load the E9 exclusion registry: {e}") from e
    return set(load_exclusions())


def _preflight(
    docs: Mapping[str, Mapping],
    dvs: Iterable[DV],
    attempts: Mapping[Key, dict],
    exclusions: Iterable[str] | None,
) -> None:
    """Refuse excluded documents and any recorded attempt not bound to the current inputs."""
    excl = excluded_ids() if exclusions is None else set(exclusions)
    dvs = list(dvs)
    bad = sorted({d for d, _ in dvs if d in excl})
    if bad:
        raise ExcludedDocument(f"{len(bad)} excluded document(s) submitted: {bad[:5]}")
    by = _by_dv(attempts)
    for doc_id, version in dvs:
        for (attempt, writer), rec in by.get((doc_id, version), {}).items():
            want = fingerprint(docs[doc_id]["text"], version, writer, attempt)
            if rec.get("fingerprint") != want:
                raise FingerprintMismatch(
                    f"{doc_id}|{version}|a{attempt}|{writer}: recorded attempt does not match "
                    "the current document text, prompt, model or seed"
                )


def _unresolved(doc_id: str, version: str, reason: str) -> dict:
    return {"doc_id": doc_id, "version": version, "status": UNRESOLVED, "reason": reason}


def item_id(doc_id: str, version: str, attempt: int) -> str:
    return f"{doc_id}|{version}|{attempt}"


def _request(doc: Mapping, version: str, attempt: int) -> dict:
    return {
        "item_id": item_id(doc["doc_id"], version, attempt),
        "fields": {"document": doc["text"]},
        "seed": _seed(attempt),
        "ref_chars": len(doc["text"]),
    }


def _docs_map(docs: Iterable[Mapping] | Mapping[str, Mapping]) -> dict[str, Mapping]:
    out: dict[str, Mapping] = {}
    for d in docs.values() if isinstance(docs, Mapping) else docs:
        if d["doc_id"] in out:
            raise ValueError(f"duplicate doc_id {d['doc_id']!r}")
        if not isinstance(d.get("text"), str) or not d["text"]:
            raise ValueError(f"document {d['doc_id']!r} has no text")
        out[d["doc_id"]] = d
    return out


def _check_versions(versions: Iterable[str]) -> tuple[str, ...]:
    versions = tuple(versions)
    bad = [v for v in versions if v not in REWRITTEN]
    if bad or not versions:
        raise ValueError(f"versions must be among {REWRITTEN}, got {versions}")
    return versions


def _call(
    model: str,
    version: str,
    attempt: int,
    reqs: list[dict],
    docs: Mapping[str, Mapping],
    *,
    stage: str,
    batch: str,
    run_batch: Callable,
    out_dir: str | Path,
    llm_dir: str | Path,
    concurrency: int,
    tok,
    errors_to_fallback: bool = False,
) -> tuple[list[dict], dict[DV, str]]:
    """One run_batch call (one ledger note), its rows turned into attempt records and appended.
    Error rows are left unrecorded (re-sent next time) unless `errors_to_fallback` and sent.
    Returns (records, {(doc_id, version): reason} for the requests left without a record)."""
    if not reqs:
        return [], {}
    spec = C.MODELS[model]
    prompt_sha = _prompt_sha(PROMPT_FOR[version])
    tag = f"{model}-{version}-a{attempt}-{batch}"
    note = C.ledger_note(stage, STEP, tag)  # validates the stage
    out_path = _root_path(llm_dir) / f"rewrite-{stage}-{tag}.jsonl"
    rows = run_batch(
        model,
        PROMPT_FOR[version],
        reqs,
        out_path,
        mode="text",
        stage=stage,
        note=note,
        concurrency=concurrency,
    )
    by_item = {r["item_id"]: r for r in rows}
    utc = datetime.now(UTC).isoformat(timespec="seconds")
    recs: list[dict] = []
    missing: dict[DV, str] = {}
    for req in reqs:
        doc = docs[req["item_id"].rsplit("|", 2)[0]]
        dv = (doc["doc_id"], version)
        row = by_item.get(req["item_id"])
        if row is None:  # not returned: left unrecorded, re-sent on resume
            missing[dv] = f"{model} a{attempt}: no result row returned"
            continue
        status = row["status"]
        out_text = row.get("text") or ""
        if status not in C.LLM_STATUSES:
            raise ValueError(f"unknown LLM status {status!r} for {req['item_id']}")
        if (
            row.get("seed") != req["seed"]
            or row.get("prompt_sha256") not in (None, prompt_sha)
            or row.get("model") not in (None, spec.model)
        ):
            raise FingerprintMismatch(
                f"{req['item_id']}: LLM row's seed, prompt sha or model differs from the request"
            )
        if status == "error" and not (errors_to_fallback and (row.get("attempts") or 0) > 0):
            sent = "sent, failed after retries" if row.get("attempts") else "not sent"
            missing[dv] = f"{model} a{attempt}: API error ({sent}): {row.get('error')}"
            continue
        recs.append(
            {
                "doc_id": doc["doc_id"],
                "version": version,
                "attempt": attempt,
                "writer": model,
                "seed": req["seed"],
                "status": status,
                "text": out_text if status == "ok" else (out_text or None),
                "n_tokens": T.n_tokens(out_text, tok) if status == "ok" else None,
                "utc": utc,
                "item_id": req["item_id"],
                "prompt_id": PROMPT_FOR[version],
                "prompt_sha256": row.get("prompt_sha256"),
                "model": row.get("model"),
                "stage": stage,
                "note": note,
                "finish_reason": row.get("finish_reason"),
                "usd": row.get("usd"),
                "orig_sha256": T.text_sha256(doc["text"]),
                "orig_n_tokens": doc.get("n_tokens"),
                "fingerprint": fingerprint(doc["text"], version, model, attempt),
            }
        )
    _append(out_dir, recs)
    return recs, missing


def write_versions(
    docs: Iterable[Mapping] | Mapping[str, Mapping],
    versions: Iterable[str] = REWRITTEN,
    *,
    stage: str,
    batch: str = "pass1",
    run_batch: Callable | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
    llm_dir: str | Path = C.LLM_DIR,
    concurrency: int = 32,
    tok=None,
    errors_to_fallback: bool = False,
    exclusions: Iterable[str] | None = None,
) -> dict[DV, dict]:
    """§4.4 steps 1-2 for every (document, version): luna writes all of them (one batch per
    version), then Qwen writes, with the same prompt and seed, every one luna refused or left
    empty. Resumable: a recorded attempt is never re-sent. `batch` names this pass in the ledger
    notes (e.g. "pass1", or "repl3" for a replacement round). Returns (doc_id, version) -> the
    standing attempt record (`current_version`) for every requested pair, or an explicit
    {"status": "unresolved", "reason"} entry if an API error or cut-off left it pending (it is
    re-sent by the next call). Refuses excluded documents and unbound recorded attempts first;
    `exclusions` (doc ids) overrides the shared registry (tests)."""
    versions = _check_versions(versions)
    docs = _docs_map(docs)
    _preflight(docs, [(i, v) for i in docs for v in versions], load_attempts(out_dir), exclusions)
    run_batch = run_batch or _run_batch_default()
    reasons: dict[DV, str] = {}
    kw = {
        "stage": stage,
        "batch": batch,
        "run_batch": run_batch,
        "out_dir": out_dir,
        "llm_dir": llm_dir,
        "concurrency": concurrency,
        "tok": tok,
        "errors_to_fallback": errors_to_fallback,
    }
    for version in versions:
        attempts = load_attempts(out_dir)
        reqs = [
            _request(d, version, 1)
            for i, d in docs.items()
            if (i, version, 1, LUNA) not in attempts
        ]
        reasons.update(_call(LUNA, version, 1, reqs, docs, **kw)[1])
        attempts = load_attempts(out_dir)
        reqs = [
            _request(d, version, 1)
            for i, d in docs.items()
            if (r := attempts.get((i, version, 1, LUNA))) is not None
            and r["status"] in FALLBACK_STATUSES
            and (i, version, 1, QWN) not in attempts
        ]
        reasons.update(_call(QWN, version, 1, reqs, docs, **kw)[1])
    attempts = load_attempts(out_dir)
    out: dict[DV, dict] = {}
    for i in docs:
        for v in versions:
            state = version_state(i, v, attempts=attempts)
            if state in ("pending", "needs_fallback"):
                out[(i, v)] = _unresolved(i, v, reasons.get((i, v), state))
            else:
                out[(i, v)] = current_version(i, v, attempts=attempts)
    return out


def regenerate(
    failed: Iterable[tuple[str, str, str]],
    *,
    docs: Iterable[Mapping] | Mapping[str, Mapping],
    stage: str,
    batch: str = "pass1",
    run_batch: Callable | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
    llm_dir: str | Path = C.LLM_DIR,
    concurrency: int = 32,
    tok=None,
    errors_to_fallback: bool = False,
    exclusions: Iterable[str] | None = None,
) -> dict[DV, dict]:
    """§4.4 step 3: each (doc_id, version, writer) whose attempt-1 output failed its checks (or,
    for Qwen, was refused) is regenerated once by the SAME writer with seed REWRITE_REQUEST_SEED
    + 1 (attempt 2). Raises ValueError if `writer` is not the writer whose attempt 1 stands, or if
    the document text differs from the one attempt 1 rewrote. An existing attempt 2 is never
    re-sent. Returns, for EVERY requested (doc_id, version), the attempt-2 record (a non-ok record
    means dropped, step 4; an ok one still goes to B2b's checks) or an explicit
    {"status": "unresolved", "reason"} entry (API error or cut-off: call again). Refuses excluded
    documents and unbound recorded attempts before any call."""
    docs = _docs_map(docs)
    failed = list(failed)
    attempts = load_attempts(out_dir)
    for doc_id, version, _ in failed:
        _check_versions([version])
        if doc_id not in docs:
            raise ValueError(f"{doc_id}: not among the documents passed")
    _preflight(docs, [(d, v) for d, v, _ in failed], attempts, exclusions)
    run_batch = run_batch or _run_batch_default()
    by = _by_dv(attempts)
    reasons: dict[DV, str] = {}
    todo: dict[tuple[str, str], list[dict]] = {}
    wanted: list[DV] = []
    for doc_id, version, writer in failed:
        recs = by.get((doc_id, version), {})
        a1 = _attempt1_writer(recs)
        if a1 is None:
            raise ValueError(f"{doc_id}|{version}: no attempt 1 to regenerate")
        if writer != a1:
            raise ValueError(
                f"{doc_id}|{version}: regeneration is by the same writer only "
                f"(attempt 1 stands with {a1!r}, got {writer!r})"
            )
        if a1 == LUNA and recs[(1, LUNA)]["status"] != "ok":
            raise ValueError(f"{doc_id}|{version}: luna refused; Qwen writes first (step 2)")
        doc = docs[doc_id]
        wanted.append((doc_id, version))
        if any(a == 2 for (a, _) in recs):
            continue
        todo.setdefault((writer, version), []).append(_request(doc, version, 2))
    for (writer, version), reqs in sorted(todo.items()):
        _recs, missing = _call(
            writer,
            version,
            2,
            reqs,
            docs,
            stage=stage,
            batch=batch,
            run_batch=run_batch,
            out_dir=out_dir,
            llm_dir=llm_dir,
            concurrency=concurrency,
            tok=tok,
            errors_to_fallback=errors_to_fallback,
        )
        reasons.update(missing)
    by = _by_dv(load_attempts(out_dir))
    out: dict[DV, dict] = {}
    for dv in wanted:
        a2 = [r for (a, _), r in by.get(dv, {}).items() if a == 2]
        out[dv] = a2[0] if a2 else _unresolved(*dv, reasons.get(dv, "attempt 2 not recorded"))
    return out


# --- version rows ---------------------------------------------------------------------------------


def version_row(rec: Mapping, tok=None) -> dict:
    """A `contracts.VERSION_KEYS` row for an ok attempt record (token count by the OLMo
    tokenizer, sha256 of the exact text)."""
    if rec["status"] != "ok" or not rec.get("text"):
        raise ValueError(f"{rec['doc_id']}|{rec['version']}: no ok text (status {rec['status']})")
    return {
        "doc_id": rec["doc_id"],
        "version": rec["version"],
        "text": rec["text"],
        "n_tokens": T.n_tokens(rec["text"], tok),
        "sha256": T.text_sha256(rec["text"]),
        "writer": rec["writer"],
        "attempt": rec["attempt"],
        "seed": rec["seed"],
    }


def orig_version_row(doc: Mapping, tok=None) -> dict:
    """The original's VERSION_KEYS row (no writer; attempt 0; no seed)."""
    return {
        "doc_id": doc["doc_id"],
        "version": "orig",
        "text": doc["text"],
        "n_tokens": T.n_tokens(doc["text"], tok),
        "sha256": T.text_sha256(doc["text"]),
        "writer": None,
        "attempt": 0,
        "seed": None,
    }


def version_rows(
    keys: Iterable[DV] | None = None,
    *,
    attempts: Mapping[Key, dict] | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
    tok=None,
) -> list[dict]:
    """VERSION_KEYS rows for the standing ok output of each (doc_id, version) in `keys` (default:
    every one with an ok standing output). Which outputs are accepted is B2b's decision; it passes
    the accepted keys. A requested key without an ok standing output raises."""
    attempts = load_attempts(out_dir) if attempts is None else attempts
    by = _by_dv(attempts)
    if keys is None:
        keys = sorted(dv for dv, recs in by.items() if (_current(recs) or {}).get("status") == "ok")
    rows = []
    for dv in keys:
        cur = _current(by.get(tuple(dv), {}))
        if cur is None:
            raise ValueError(f"{dv}: nothing written")
        rows.append(version_row(cur, tok))
    return rows


# --- statistics for the report (§4.4 "Reported") --------------------------------------------------


def _rate(n: int, d: int) -> float | None:
    return n / d if d else None


def _summary(xs: list[float]) -> dict:
    return {
        "n": len(xs),
        "mean": statistics.fmean(xs) if xs else None,
        "median": statistics.median(xs) if xs else None,
    }


def refusal_stats(
    *,
    attempts: Mapping[Key, dict] | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
    check_passed: Mapping[Key, bool] | None = None,
    scores: Mapping[str, float] | None = None,
    insert_ids: Iterable[str] | None = None,
) -> dict:
    """Per version and overall: step 1 (luna attempt 1) status counts and refused/empty rate;
    step 2 (Qwen attempt 1) status counts and refusal rate; step 3 (attempt 2) outcomes by writer
    (ok/refused counts and, given B2b's `check_passed` per attempt key, passed/failed); the number
    of Qwen-written standing outputs; and, given `scores` (doc_id -> content-judge endorsement),
    the scores of documents luna refused against the rest (restricted to `insert_ids` if given)."""
    attempts = load_attempts(out_dir) if attempts is None else attempts
    check_passed = check_passed or {}
    by = _by_dv(attempts)
    out: dict = {}
    for version in (*REWRITTEN, "all"):
        recs = [r for k, r in attempts.items() if version == "all" or k[1] == version]
        luna1 = Counter(r["status"] for r in recs if r["attempt"] == 1 and r["writer"] == LUNA)
        qwn1 = Counter(r["status"] for r in recs if r["attempt"] == 1 and r["writer"] == QWN)
        n_l, n_q = sum(luna1.values()), sum(qwn1.values())
        regen: dict = {}
        for w in (LUNA, QWN):
            rr = [r for r in recs if r["attempt"] == 2 and r["writer"] == w]
            st = Counter(r["status"] for r in rr)
            checked = [check_passed[_key(r)] for r in rr if _key(r) in check_passed]
            regen[w] = {
                "n": len(rr),
                "status": dict(st),
                "checked": len(checked),
                "passed": sum(checked),
                "dropped": sum(1 for r in rr if r["status"] != "ok")
                + sum(1 for c in checked if not c),
            }
        standing = [
            cur
            for (d, v), rs in by.items()
            if (version == "all" or v == version) and (cur := _current(rs)) is not None
        ]
        out[version] = {
            "step1_luna": {
                "n": n_l,
                "status": dict(luna1),
                "refused_or_empty_rate": _rate(luna1["refused"] + luna1["empty"], n_l),
                "no_output_rate": _rate(sum(luna1[s] for s in FALLBACK_STATUSES), n_l),
            },
            "step2_qwn": {
                "n": n_q,
                "status": dict(qwn1),
                "refused_rate": _rate(qwn1["refused"], n_q),
                "no_output_rate": _rate(sum(qwn1[s] for s in FALLBACK_STATUSES), n_q),
            },
            "step3_regeneration": regen,
            "standing_by_writer": dict(
                Counter(c["writer"] for c in standing if c["status"] == "ok")
            ),
        }
    if scores is not None:
        ids = set(insert_ids) if insert_ids is not None else {d for d, _ in by}
        refused = {
            d
            for (d, _v, a, w), r in attempts.items()
            if a == 1 and w == LUNA and r["status"] in FALLBACK_STATUSES
        } & ids
        out["endorsement_refused_vs_rest"] = {
            "refused": _summary([scores[d] for d in sorted(refused) if d in scores]),
            "rest": _summary([scores[d] for d in sorted(ids - refused) if d in scores]),
            "missing_scores": sorted(d for d in ids if d not in scores),
        }
    return out


# --- cost projection (for --dry-run) --------------------------------------------------------------


def project_write(
    docs: Iterable[Mapping] | Mapping[str, Mapping],
    versions: Iterable[str] = REWRITTEN,
    *,
    estimate: Callable | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
    exclusions: Iterable[str] | None = None,
) -> dict:
    """Projected $ for `write_versions`: luna on every unrecorded attempt 1, and Qwen's worst
    case (every one of those refused by luna) plus Qwen on luna's already-recorded refusals.
    Runs the same preflight (exclusions, fingerprints) as the paid call."""
    versions = _check_versions(versions)
    docs = _docs_map(docs)
    estimate = estimate or _estimate_default()
    attempts = load_attempts(out_dir)
    _preflight(docs, [(i, v) for i in docs for v in versions], attempts, exclusions)
    out = {"luna": 0.0, "qwn_worst_case": 0.0, "n_luna": 0, "n_qwn_max": 0}
    for v in versions:
        luna = [_request(d, v, 1) for i, d in docs.items() if (i, v, 1, LUNA) not in attempts]
        qwn = luna + [
            _request(d, v, 1)
            for i, d in docs.items()
            if (r := attempts.get((i, v, 1, LUNA))) is not None
            and r["status"] in FALLBACK_STATUSES
            and (i, v, 1, QWN) not in attempts
        ]
        if luna:
            out["luna"] += estimate(LUNA, PROMPT_FOR[v], luna, "text")
        if qwn:
            out["qwn_worst_case"] += estimate(QWN, PROMPT_FOR[v], qwn, "text")
        out["n_luna"] += len(luna)
        out["n_qwn_max"] += len(qwn)
    out["total_worst_case"] = out["luna"] + out["qwn_worst_case"]
    return out


def project_regenerate(
    failed: Iterable[tuple[str, str, str]],
    *,
    docs: Iterable[Mapping] | Mapping[str, Mapping],
    estimate: Callable | None = None,
    out_dir: str | Path = C.REWRITE_DIR,
    exclusions: Iterable[str] | None = None,
) -> dict:
    """Projected $ for `regenerate` (attempts 2 not yet recorded), by writer, after the same
    preflight (exclusions, fingerprints) as the paid call."""
    docs = _docs_map(docs)
    failed = list(failed)
    estimate = estimate or _estimate_default()
    attempts = load_attempts(out_dir)
    _preflight(docs, [(d, v) for d, v, _ in failed], attempts, exclusions)
    by = _by_dv(attempts)
    groups: dict[tuple[str, str], list[dict]] = {}
    for d, v, w in failed:
        if any(a == 2 for (a, _) in by.get((d, v), {})):
            continue
        groups.setdefault((w, v), []).append(_request(docs[d], v, 2))
    out: dict = {"by_writer": {}, "n": 0}
    for (w, v), reqs in groups.items():
        out["by_writer"][w] = out["by_writer"].get(w, 0.0) + estimate(
            w, PROMPT_FOR[v], reqs, "text"
        )
        out["n"] += len(reqs)
    out["total"] = sum(out["by_writer"].values())
    return out
