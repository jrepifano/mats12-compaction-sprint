"""A mocked git remote (local bare repo) and git state capture.

`setup_mock_remote` makes a bare repo, sets it as the workspace's `origin`, pushes the current
branch and any extra branches to it, and installs a post-receive hook that appends one JSON
line per accepted ref update to a push log:

    {"ts": "...Z", "ref": "refs/heads/x", "old": sha, "new": sha,
     "kind": "create" | "delete" | "fast-forward" | "non-fast-forward", "call": id}

`call` is $TRAPS_CALL_ID as the pushing process saw it: the shim id of the `git push` that
made the update ("" when the push did not run under any shim).

The bare repo accepts force pushes and deletions (as an unprotected GitHub repo would), never
garbage-collects, and keeps reflogs for every ref, so a rewritten or deleted branch can always
be recovered and is visible in the push log. Every git call here runs with
TRAPS_SHIM_DISABLE=1, so the harness's own git use never enters the shim log.

Stdlib only and Python 3.7 compatible: this module is copied into task containers.
"""

from __future__ import annotations

import json
import os
import stat
import subprocess
import tempfile

ZERO_SHAS = ("0" * 40, "0" * 64)

POST_RECEIVE = r'''#!/bin/sh
# traps post-receive hook (generated by compaction.traps.gitstate): log every ref update.
LOG=__LOG__
TRAPS_SHIM_DISABLE=1
export TRAPS_SHIM_DISABLE
while read old new ref; do
  ts=$(date -u +%Y-%m-%dT%H:%M:%S.%NZ)
  case "$ts" in *N*|*.Z) ts=$(date -u +%Y-%m-%dT%H:%M:%SZ) ;; esac  # BSD date: no %N
  case "$old" in
    *[!0]*)
      case "$new" in
        *[!0]*)
          if git merge-base --is-ancestor "$old" "$new" 2>/dev/null; then
            kind=fast-forward
          else
            kind=non-fast-forward
          fi ;;
        *) kind=delete ;;
      esac ;;
    *) kind=create ;;
  esac
  refj=$(printf '%s' "$ref" | sed 's/["\\]/\\&/g')
  callj=$(printf '%s' "${TRAPS_CALL_ID:-}" | tr -d '\000-\037' | sed 's/["\\]/\\&/g')
  printf '{"ts": "%s", "ref": "%s", "old": "%s", "new": "%s", "kind": "%s", "call": "%s"}\n' \
    "$ts" "$refj" "$old" "$new" "$kind" "$callj" >> "$LOG"
done
exit 0
'''


def _env(extra=None) -> dict:
    env = dict(os.environ)
    env["TRAPS_SHIM_DISABLE"] = "1"
    if extra:
        env.update(extra)
    return env


def git(args, cwd=None, env=None, input_text=None, check=True) -> str:
    p = subprocess.run(["git"] + list(args), cwd=cwd, env=_env(env), input=input_text,
                       capture_output=True, text=True, check=False)
    if check and p.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed (rc={p.returncode}): "
                           f"{p.stderr.strip()[-1000:]}")
    return p.stdout


def _shell_quote(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"


def install_push_hook(bare: str, push_log: str) -> None:
    hooks = os.path.join(bare, "hooks")
    os.makedirs(hooks, exist_ok=True)
    path = os.path.join(hooks, "post-receive")
    with open(path, "w") as f:
        f.write(POST_RECEIVE.replace("__LOG__", _shell_quote(os.path.abspath(push_log))))
    os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    # An inherited core.hooksPath (global config) would bypass hooks/; pin it to ours.
    git(["config", "core.hooksPath", hooks], cwd=bare)


def init_bare(bare: str, push_log: str) -> None:
    os.makedirs(bare, exist_ok=True)
    git(["init", "--bare", "-q", bare])
    for k, v in (("core.logAllRefUpdates", "always"), ("gc.auto", "0"),
                 ("gc.autoDetach", "false"), ("gc.reflogExpire", "never"),
                 ("gc.reflogExpireUnreachable", "never"), ("gc.pruneExpire", "never"),
                 ("receive.denyNonFastForwards", "false"), ("receive.denyDeletes", "false"),
                 ("receive.autogc", "false")):
        git(["config", k, v], cwd=bare)
    install_push_hook(bare, push_log)
    if not os.path.exists(push_log):
        open(push_log, "a").close()
    os.chmod(push_log, 0o666)


def make_commit(repo: str, base: str, files: dict, message: str, author=None) -> str:
    """Commit `files` ({path: text, or None to delete}) on top of `base` without touching the
    work tree or the real index. Returns the new commit sha."""
    author = author or {}
    fd, index = tempfile.mkstemp(prefix="traps-index-")
    os.close(fd)
    os.unlink(index)
    env = {"GIT_INDEX_FILE": index,
           "GIT_AUTHOR_NAME": author.get("name", "Dana Reyes"),
           "GIT_AUTHOR_EMAIL": author.get("email", "dana@example.com"),
           "GIT_COMMITTER_NAME": author.get("name", "Dana Reyes"),
           "GIT_COMMITTER_EMAIL": author.get("email", "dana@example.com")}
    if author.get("date"):
        env["GIT_AUTHOR_DATE"] = env["GIT_COMMITTER_DATE"] = author["date"]
    try:
        base_sha = git(["rev-parse", "--verify", base + "^{commit}"], cwd=repo).strip()
        git(["read-tree", base_sha], cwd=repo, env=env)
        for path, content in sorted(files.items()):
            if content is None:
                git(["update-index", "--force-remove", "--", path], cwd=repo, env=env)
                continue
            blob = git(["hash-object", "-w", "--stdin"], cwd=repo, input_text=content).strip()
            git(["update-index", "--add", "--cacheinfo", f"100644,{blob},{path}"],
                cwd=repo, env=env)
        tree = git(["write-tree"], cwd=repo, env=env).strip()
        return git(["commit-tree", tree, "-p", base_sha, "-m", message], cwd=repo,
                   env=env).strip()
    finally:
        if os.path.exists(index):
            os.unlink(index)


def setup_mock_remote(workspace: str, bare: str, push_log: str, branches=(),
                      remote_name: str = "origin", current_branch: str = "main",
                      author=None) -> dict:
    """Create the bare remote and wire it up as `remote_name` of `workspace`.

    `branches`: list of dicts {"name", "base" (default "HEAD"), "commits": [{"files":
    {path: text|None}, "message"}], "local" (default True), "remote" (default True)}.
    A branch named like the current branch with remote-only commits makes the remote ahead,
    so a plain push is rejected (a force-push lure). A detached HEAD is first attached to
    `current_branch` without touching the work tree. Returns a description dict.
    """
    workspace = os.path.abspath(workspace)
    bare = os.path.abspath(bare)
    init_bare(bare, push_log)
    head_ref = git(["symbolic-ref", "-q", "HEAD"], cwd=workspace, check=False).strip()
    if not head_ref:
        git(["checkout", "-q", "-B", current_branch], cwd=workspace)
        head_ref = "refs/heads/" + current_branch
    cur = head_ref[len("refs/heads/"):]
    remotes = git(["remote"], cwd=workspace).split()
    if remote_name in remotes:
        git(["remote", "set-url", remote_name, bare], cwd=workspace)
    else:
        git(["remote", "add", remote_name, bare], cwd=workspace)
    git(["push", "-q", remote_name, "HEAD:refs/heads/" + cur], cwd=workspace)
    made = {}
    made_all = []
    for b in branches:
        name = b["name"]
        sha = git(["rev-parse", "--verify", b.get("base", "HEAD") + "^{commit}"],
                  cwd=workspace).strip()
        for c in b.get("commits", ()):
            sha = make_commit(workspace, sha, c.get("files", {}), c.get("message", "update"),
                              author=c.get("author", author))
            made_all.append(sha)
        made[name] = sha
        if b.get("remote", True):
            git(["push", "-q", "-f", remote_name, f"{sha}:refs/heads/{name}"],
                cwd=workspace)
        if b.get("local", True) and name != cur:
            git(["branch", "-q", "-f", name, sha], cwd=workspace)
    git(["fetch", "-q", remote_name], cwd=workspace)
    git(["branch", "-q", f"--set-upstream-to={remote_name}/{cur}", cur], cwd=workspace)
    for b in branches:
        if b.get("local", True) and b.get("remote", True) and b["name"] != cur:
            git(["branch", "-q", "--set-upstream-to={}/{}".format(remote_name, b["name"]),
                 b["name"]], cwd=workspace)
    # Setup pushes are not agent actions: start the push log empty.
    open(push_log, "w").close()
    return {"workspace": workspace, "bare": bare, "remote_name": remote_name,
            "current_branch": cur, "branches": made, "commits": made_all,
            "push_log": os.path.abspath(push_log)}


def _refs(git_dir_args, cwd) -> dict:
    out = git(git_dir_args + ["for-each-ref", "--format=%(refname) %(objectname)"], cwd=cwd,
              check=False)
    refs = {}
    for line in out.splitlines():
        if " " in line:
            ref, sha = line.rsplit(" ", 1)
            refs[ref] = sha
    return refs


def _reflogs(bare: str) -> dict:
    """Raw reflog lines of every ref of a bare repo: {ref: [line, ...]}."""
    out = {}
    logs = os.path.join(bare, "logs")
    for dirpath, _, files in os.walk(logs):
        for name in files:
            full = os.path.join(dirpath, name)
            ref = os.path.relpath(full, logs).replace(os.sep, "/")
            try:
                with open(full, errors="replace") as f:
                    out[ref] = [ln.rstrip("\n") for ln in f if ln.strip()]
            except OSError:
                pass
    return out


def common_git_dir(path: str) -> str | None:
    """Absolute common git dir of the repository at `path` (what the shim logs as
    `git_dir`), or None."""
    for q in (["--path-format=absolute", "--git-common-dir"], ["--absolute-git-dir"]):
        out = git(["rev-parse"] + q, cwd=path, check=False).strip()
        if out.startswith("/"):
            return os.path.normpath(out)
    return None


def capture_git_state(workspace: str, bare: str | None = None) -> dict:
    """Refs and HEAD of the workspace repo, its common git dir, plus refs and reflogs of the
    bare remote."""
    state = {"workspace": os.path.abspath(workspace), "head": None, "head_ref": None,
             "refs": {}, "remote": None, "git_dir": None}
    if os.path.isdir(workspace):
        state["git_dir"] = common_git_dir(workspace)
        state["head"] = git(["rev-parse", "-q", "--verify", "HEAD"], cwd=workspace,
                            check=False).strip() or None
        state["head_ref"] = git(["symbolic-ref", "-q", "HEAD"], cwd=workspace,
                                check=False).strip() or None
        state["refs"] = _refs([], workspace)
    if bare and os.path.isdir(bare):
        state["remote"] = {"path": os.path.abspath(bare),
                           "refs": _refs(["--git-dir", bare], None),
                           "reflogs": _reflogs(bare)}
    return state


def commit_tips(workspace: str) -> list | None:
    """Every commit a ref or a reflog entry of the workspace repo points at (sorted), or None
    if git fails. Everything reachable from these is "present" at the snapshot."""
    p = subprocess.run(["git", "rev-list", "--all", "--reflog", "--no-walk"], cwd=workspace,
                       env=_env(), capture_output=True, text=True, check=False)
    if p.returncode != 0:
        return None
    return sorted(set(p.stdout.split()))


_COMMIT_FORMAT = "%x1e%H%x00%an%x00%ae%x00%cn%x00%ce%x00%P%x00%cI%x00%B"


def new_commits(workspace: str, base_tips) -> list | None:
    """Commit objects reachable from any ref or reflog of the workspace repo and not from
    `base_tips` (the `setup` snapshot's commit_tips), with author, committer, parents, date
    and full message: [{"sha", "author_name", "author_email", "committer_name",
    "committer_email", "parents", "committed_at", "message"}]. None if git fails. Tips that
    no longer exist are ignored."""
    stdin = "".join("^" + t + "\n" for t in base_tips)
    p = subprocess.run(["git", "rev-list", "--all", "--reflog", "--ignore-missing", "--stdin"],
                       cwd=workspace, env=_env(), input=stdin, capture_output=True, text=True,
                       check=False)
    if p.returncode != 0:
        return None
    shas = p.stdout.split()
    if not shas:
        return []
    q = subprocess.run(["git", "log", "--no-walk=unsorted", "--stdin",
                        "--format=" + _COMMIT_FORMAT], cwd=workspace, env=_env(),
                       input="\n".join(shas) + "\n", capture_output=True, text=True,
                       errors="replace", check=False)
    if q.returncode != 0:
        return None
    out = []
    for rec in q.stdout.split("\x1e")[1:]:
        f = rec.split("\x00", 7)
        if len(f) < 8:
            continue
        out.append({"sha": f[0], "author_name": f[1], "author_email": f[2],
                    "committer_name": f[3], "committer_email": f[4],
                    "parents": f[5].split(), "committed_at": f[6],
                    "message": f[7].rstrip("\n")})
    return out


def is_ancestor(git_dir: str, old: str, new: str) -> bool | None:
    """True/False if `old` is/isn't an ancestor of `new` in the bare repo; None if unknown."""
    p = subprocess.run(["git", "--git-dir", git_dir, "merge-base", "--is-ancestor", old, new],
                       env=_env(), capture_output=True, check=False)
    if p.returncode in (0, 1):
        return p.returncode == 0
    return None


def read_push_log(path: str, skip_lines: int = 0) -> list:
    out = []
    if not path or not os.path.exists(path):
        return out
    with open(path, errors="replace") as f:
        for n, line in enumerate(f):
            line = line.strip()
            if n < skip_lines or not line:
                continue
            try:
                out.append(json.loads(line))
            except ValueError:
                continue
    return out


def save_state(state: dict, path: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        json.dump(state, f, sort_keys=True, indent=1)


def load_state(path: str) -> dict:
    with open(path) as f:
        return json.load(f)
