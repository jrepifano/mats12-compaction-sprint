"""PATH-injected shell shim: wrapper scripts that log each call, then run the real binary.

`install_shims(bin_dir, log_path)` writes one small Python script per command into `bin_dir`.
Put `bin_dir` first on the agent's PATH. Each call appends two JSON lines to `log_path`:

    {"id", "phase": "start", "ts", "cmd", "argv", "cwd", "pid", "ppid", "depth", "real",
     "git_dir" (git calls only)}
    {"id", "phase": "end", "ts", "exit_code", "signal"}

`argv[0]` is the command name. For git, `git_dir` is the repository the call acts on, as git
itself resolves it before the call runs (`git <-C/--git-dir/--work-tree> rev-parse
--git-common-dir`, with the call's cwd and environment, so GIT_DIR and nested repos count);
None if there is no repository yet (`git init`, `clone`). This costs one extra git process
per shimmed git call. The start line is written before the real binary runs, so a
command that hangs and is killed still leaves its argv. Calls made from inside another shimmed
call (git calling rm, `xargs rm`) carry depth >= 1. Because the shim is found through PATH,
`bash -c "rm -rf x"`, `xargs`, `find -exec` and `env` all go through it; absolute paths
(`/bin/rm`), `python -c "os.remove(...)"` and editor tools do not, which is why the filesystem
snapshots and the mocked remote's push log are the ground truth and the shim is attribution.

Environment knobs read by the shim at run time:
- TRAPS_SHIM_LOG: overrides the log path baked in at install time;
- TRAPS_SHIM_DISABLE=1: pass straight through without logging (for the harness's own commands);
- TRAPS_SHIM_DEPTH: set by the shim for its children;
- TRAPS_CALL_ID: set by the shim for its children to the call's id. The mocked remote's
  post-receive hook writes it into the push log, so each ref update names the shimmed call
  that made it (a push that bypassed the shim has none, or its enclosing call's).

The shim never changes the command's behaviour: stdin/stdout/stderr are inherited, the exit
code is propagated, a child killed by a signal makes the shim die by the same signal, and a
logging failure is swallowed. Python >= 3.7 in the container.
"""

from __future__ import annotations

import json
import os
import shutil
import stat

# Commands shimmed by default (only those found on PATH at install time are installed).
DEFAULT_COMMANDS = (
    "git", "rm", "rmdir", "unlink", "mv", "cp", "chmod", "chown", "ln", "touch", "truncate",
    "mkdir", "find", "rsync", "curl", "wget", "ssh", "scp", "pip", "pip3", "npm", "npx", "yarn",
    "pnpm", "uv", "sudo",
)

SHIM_TEMPLATE = r'''#!__PYTHON__
# traps shell shim (generated by compaction.traps.shim). Logs the call, then runs the real binary.
import json, os, signal, subprocess, sys, time
SHIM_DIR = __SHIM_DIR__
LOG = os.environ.get("TRAPS_SHIM_LOG") or __LOG__
REAL = __REAL__
NAME = os.path.basename(sys.argv[0])


def utc():
    t = time.time()
    return time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(t)) + ".%06dZ" % int((t % 1) * 1e6)


def find_real():
    me = os.path.realpath(__file__)
    shim_real = os.path.realpath(SHIM_DIR)
    for d in os.environ.get("PATH", "").split(os.pathsep):
        if not d:
            continue
        try:
            if os.path.realpath(d) == shim_real:
                continue
        except OSError:
            continue
        p = os.path.join(d, NAME)
        if os.path.isfile(p) and os.access(p, os.X_OK) and os.path.realpath(p) != me:
            return p
    p = REAL.get(NAME)
    if p and os.path.isfile(p) and os.access(p, os.X_OK):
        return p
    return None


def repo_of(real, args):
    """The common git dir this git call would use, or None."""
    pre, i = [], 0
    while i < len(args) and args[i].startswith("-"):
        a = args[i]
        name = a.split("=", 1)[0]
        if name in ("-C", "--git-dir", "--work-tree"):
            if "=" in a:
                pre.append(a)
            elif i + 1 < len(args):
                pre += [a, args[i + 1]]
                i += 1
        elif a in ("-c", "--namespace", "--exec-path", "--super-prefix", "--config-env",
                   "--list-cmds", "--attr-source"):
            i += 1
        i += 1
    env = dict(os.environ)
    env["TRAPS_SHIM_DISABLE"] = "1"
    for q in (["--path-format=absolute", "--git-common-dir"], ["--absolute-git-dir"]):
        try:
            p = subprocess.run([real] + pre + ["rev-parse"] + q, env=env, timeout=10,
                               stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                               stdin=subprocess.DEVNULL)
        except Exception:
            return None
        out = p.stdout.decode("utf-8", "surrogateescape").strip()
        if p.returncode == 0 and out.startswith("/"):
            return os.path.normpath(out)
    return None


def log(rec):
    try:
        import fcntl
        line = (json.dumps(rec, ensure_ascii=True) + "\n").encode()
        fd = os.open(LOG, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o666)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX)
            os.write(fd, line)
        finally:
            os.close(fd)
    except Exception:
        pass


def main():
    real = find_real()
    args = sys.argv[1:]
    if os.environ.get("TRAPS_SHIM_DISABLE") == "1" and real:
        os.execv(real, [NAME] + args)
    try:
        depth = int(os.environ.get("TRAPS_SHIM_DEPTH", "0"))
    except ValueError:
        depth = 0
    if depth > 32 and real:  # runaway recursion guard: stop logging, just run it
        os.execv(real, [NAME] + args)
    rid = "%d-%s" % (os.getpid(), os.urandom(6).hex())
    try:
        cwd = os.getcwd()
    except OSError:
        cwd = None
    rec = {"id": rid, "phase": "start", "ts": utc(), "cmd": NAME, "argv": [NAME] + args,
           "cwd": cwd, "pid": os.getpid(), "ppid": os.getppid(), "depth": depth, "real": real}
    if NAME == "git" and real:
        rec["git_dir"] = repo_of(real, args)
    log(rec)
    if real is None:
        sys.stderr.write("%s: command not found\n" % NAME)
        log({"id": rid, "phase": "end", "ts": utc(), "exit_code": 127, "signal": None})
        sys.exit(127)
    env = dict(os.environ)
    env["TRAPS_SHIM_DEPTH"] = str(depth + 1)
    env["TRAPS_CALL_ID"] = rid
    try:
        child = subprocess.Popen([NAME] + args, executable=real, env=env)
    except OSError as e:
        sys.stderr.write("%s: %s\n" % (NAME, e))
        log({"id": rid, "phase": "end", "ts": utc(), "exit_code": 126, "signal": None})
        sys.exit(126)

    def forward(signum, frame):
        try:
            child.send_signal(signum)
        except OSError:
            pass

    for s in ("SIGTERM", "SIGHUP", "SIGQUIT", "SIGUSR1", "SIGUSR2"):
        if hasattr(signal, s):
            signal.signal(getattr(signal, s), forward)
    # SIGINT reaches the child through the process group; the shim just waits for it.
    signal.signal(signal.SIGINT, signal.SIG_IGN)
    while True:
        try:
            rc = child.wait()
            break
        except InterruptedError:
            continue
    sig = -rc if rc < 0 else None
    log({"id": rid, "phase": "end", "ts": utc(), "exit_code": 128 + sig if sig else rc,
         "signal": sig})
    if sig:
        signal.signal(sig, signal.SIG_DFL)
        os.kill(os.getpid(), sig)
    sys.exit(rc)


main()
'''


def render_shim(shim_dir: str, log_path: str, python: str, real: dict) -> str:
    return (SHIM_TEMPLATE.replace("__PYTHON__", python)
            .replace("__SHIM_DIR__", repr(shim_dir))
            .replace("__LOG__", repr(log_path))
            .replace("__REAL__", repr(dict(real))))


def install_shims(bin_dir: str, log_path: str, commands=DEFAULT_COMMANDS,
                  python: str | None = None, search_path: str | None = None) -> dict:
    """Write a shim for each command found on `search_path` (default: $PATH minus `bin_dir`).

    Returns {command: real path} for the commands installed. `python` is the interpreter the
    shims run under (default: the current one); it must stay put for the whole run.
    """
    import sys

    bin_dir = os.path.abspath(bin_dir)
    log_path = os.path.abspath(log_path)
    python = python or sys.executable
    os.makedirs(bin_dir, exist_ok=True)
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    path = search_path if search_path is not None else os.environ.get("PATH", "")
    path = os.pathsep.join(d for d in path.split(os.pathsep)
                           if d and os.path.abspath(d) != bin_dir)
    real = {}
    for cmd in commands:
        p = shutil.which(cmd, path=path)
        if p:
            real[cmd] = p
    for cmd in real:
        dest = os.path.join(bin_dir, cmd)
        with open(dest, "w") as f:
            f.write(render_shim(bin_dir, log_path, python, real))
        os.chmod(dest, os.stat(dest).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    if not os.path.exists(log_path):
        open(log_path, "a").close()
    os.chmod(log_path, 0o666)
    return real


def read_shim_log(path: str, skip_lines: int = 0) -> list:
    """Join start/end lines into one dict per call, in start order.

    Each call: id, cmd, argv, cwd, ts (start), ts_end, exit_code (None if the end line is
    missing, i.e. the shim was killed), signal, depth, pid, ppid, real. Malformed lines are
    skipped silently: a half-written last line is expected if the container was killed.
    The first `skip_lines` lines are ignored, and so are end lines whose start was skipped.
    """
    calls = {}
    order = []
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", errors="surrogateescape") as f:
        for n, line in enumerate(f):
            line = line.strip()
            if n < skip_lines or not line:
                continue
            try:
                rec = json.loads(line)
            except ValueError:
                continue
            rid = rec.get("id")
            if rec.get("phase") == "start":
                c = {k: v for k, v in rec.items() if k != "phase"}
                c.setdefault("ts_end", None)
                c.setdefault("exit_code", None)
                c.setdefault("signal", None)
                calls[rid] = c
                order.append(rid)
            elif rec.get("phase") == "end" and rid in calls:
                calls[rid]["ts_end"] = rec.get("ts")
                calls[rid]["exit_code"] = rec.get("exit_code")
                calls[rid]["signal"] = rec.get("signal")
    return [calls[r] for r in order]
