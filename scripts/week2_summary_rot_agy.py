"""Summary rot, pi beside agy on the same four unrelated chains (u1–u4), in summary_rot's style.

Reads week2-build's agy readout at a pinned commit (git show, nothing copied): agy's cells are
`composition.cells.final`, pi's are `pi.rot.cells.final` (pi's u1–u4 subset recomputed from this
branch's attributions at e9a4c51f; the readout's `recompute_check` compares it with shares.json).
Both sides were labelled by week2_summary_rot.py's coder unchanged at e9a4c51f (code, then Claude
Opus 5.5). Plotting only; no model calls.

    uv run python scripts/week2_summary_rot_agy.py
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import week2_summary_rot as R

REF = "55d08ed4"  # sprint/week2-build: agy five-task chains, summary rot with this coder
SRC = "results/sprint/week2/agy_chain5/agy/bulk/readout.json"
OUT = R.OUT / "agy_vs_pi"
SIDES = (("pi", "pi (DeepSeek V4.1 Flash)"), ("agy", "Antigravity (Gemini 3.8 Flash, low)"))


def main() -> None:
    raw = subprocess.run(["git", "show", f"{REF}:{SRC}"], cwd=R.ROOT, check=True,
                         capture_output=True).stdout
    d = json.loads(raw)
    chk = d["pi"]["rot"]["recompute_check"]
    if chk["max_abs_diff"] != 0:
        sys.exit(f"pi u1–u4 cells differ from shares.json: {chk}")
    cells = {"agy": d["composition"]["cells"]["final"], "pi": d["pi"]["rot"]["cells"]["final"]}
    if not d["composition"].get("opus_complete"):
        sys.exit("agy attribution incomplete (opus_complete false)")
    plt, colors = R._style()
    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch

    def later(side):
        return [100 * c["earlier"] for k, c in cells[side].items() if int(k) >= 2]

    pl, al = later("pi"), later("agy")
    a_txt = (f"{max(al):.0f}%" if min(al) == max(al) else f"{min(al):.0f}–{max(al):.0f}%")
    title = (f"On the same four chains, Antigravity's summaries are {a_txt} about earlier tasks after "
             f"tasks 2–4; pi's are {min(pl):.0f}–{max(pl):.0f}% on average")
    OUT.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(14, 6.2), sharey=True)
    fig.subplots_adjust(left=0.06, right=0.985, top=0.84, bottom=0.2, wspace=0.06)
    nums = []
    for ax, (side, label) in zip(axes, SIDES, strict=True):
        nums += R._panel(ax, cells[side], colors, label)
    axes[0].set_ylabel("Share of summary entries (%)")
    fig.suptitle(title, x=0.02, y=0.975, ha="left", va="top")
    handles = [Patch(color=colors[c], label=R.CAT_LABEL[c]) for c in R.FIG_CATS[::-1]]
    handles.append(Line2D([], [], marker="o", color="black",
                          label="Earlier tasks total (95% CI)"))
    fig.legend(handles=handles, loc="lower center", ncol=3, bbox_to_anchor=(0.5, 0.0))
    for ext in ("png", "svg"):
        fig.savefig(OUT / f"summary_rot_agy_vs_pi.{ext}", dpi=200 if ext == "png" else None)
    plt.close(fig)
    comp = d["composition"]
    mp = comp["minus_pi"]
    diffs = "; ".join(f"after task {k}: {100 * v['diff']:+.1f} points [{100 * v['ci95'][0]:+.1f}, "
                      f"{100 * v['ci95'][1]:+.1f}], pi higher in {v['signs']['b_higher']} of "
                      f"{len(v['eligible_chains'])} chains"
                      for k, v in sorted(mp.items(), key=lambda kv: int(kv[0])))
    readme = [
        "# Summary rot: pi beside agy (week 2, experiment 4's unrelated chains u1–u4)", "",
        ("Generated by `scripts/week2_summary_rot_agy.py` from "
         f"`{REF}:{SRC}` (sha256 {hashlib.sha256(raw).hexdigest()[:16]}…); every number is read "
         "from that file."), "",
        f"## summary_rot_agy_vs_pi: {title}", "", "![summary_rot_agy_vs_pi](summary_rot_agy_vs_pi.png)",
        "",
        ("**Source:** agy, `composition.cells.final.<k>`; pi, `pi.rot.cells.final.<k>` (pi's "
         "u1–u4 subset, recomputed from `e9a4c51f:results/sprint/week2/chain_stress/summary_rot/"
         f"attributions.jsonl`; matches shares.json on {chk['n_values']} values, max difference "
         f"{chk['max_abs_diff']})."), "",
        ("**Caption (slide notes, not on the figure):** agy (Gemini 3.8 Flash, low) against pi "
         "(DeepSeek V4.1 Flash) on the same four chains (u1–u4), labelled by the same coder "
         "(`scripts/week2_summary_rot.py` at e9a4c51f: name matching, else Claude Opus 5.5). Model "
         "and harness differ together, so this does not separate the two. agy keeps the earlier "
         "tasks only as the user's verbatim requests, outside its summary; those kept requests are "
         "not counted here."), "",
        f"**agy minus pi, earlier-task share (paired bootstrap over chains, from `composition.minus_pi`):** {diffs}.",
        "",
        (f"**Notes:** means over chains (each chain weighs the same); black whisker: 95% bootstrap "
         f"interval over chains, shown only where the share is above 0 (agy's is 0 at every "
         f"boundary, interval [0, 0]). Entries: {comp['n_entries']} lines in {comp['n_summaries']} "
         "agy summaries, including the end summaries after task 5, which are not plotted (pi has "
         "none to match). n = 4 chains per side, so the intervals are coarse."), "",
        "**Numbers plotted:**"] + [f"- {n}" for n in nums]
    (OUT / "README.md").write_text("\n".join(readme) + "\n")
    print(f"wrote {R.rel(OUT)}")


if __name__ == "__main__":
    main()
