def _sha(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def opus_check(sample: list[dict], args) -> dict:
    """{id: bool} from Opus, two calls of SAMPLE_PER_CLASS entries, cached per call."""
    from compaction.s1_types import Req

    schema = {"type": "object", "additionalProperties": False, "required": ["labels"],
              "properties": {"labels": {"type": "array", "items": {
                  "type": "object", "additionalProperties": False,
                  "required": ["i", "safety_relevant"],
                  "properties": {"i": {"type": "integer"},
                                 "safety_relevant": {"type": "boolean"}}}}}}
    out, todo = {}, []
    for b in range(0, len(sample), SAMPLE_PER_CLASS):
        part = sample[b:b + SAMPLE_PER_CLASS]
        user = "\n".join([f'<lines count="{len(part)}">']
                         + [f"[{i}] {r['text'].strip()}" for i, r in enumerate(part, 1)]
                         + ["</lines>", "", (f'Return "labels": {len(part)} objects, '
                                             f"i = 1..{len(part)} in order.")])
        key = f"safety:{b // SAMPLE_PER_CLASS}"
        cache = OPUS_DIR / f"call{b // SAMPLE_PER_CLASS}.json"
        sha = _sha(SYSTEM + "\0" + user)
        if cache.exists() and json.loads(cache.read_text()).get("prompt_sha256") == sha:
            ans = json.loads(cache.read_text())["labels"]
        else:
            if args.no_opus:
                continue
            todo.append((key, cache, sha, part, Req(key=key, system=SYSTEM, user=user,
                                                    schema=schema, max_output_tokens=8000,
                                                    rid=key, source="chain", private=False)))
            continue
        out.update({r["id"]: a for r, a in zip(part, ans, strict=True)})
    if todo:
        be = SRS.backend(2)
        resps = be.run([t[4] for t in todo], purpose="week2-summary-decay")
        for key, cache, sha, part, _ in todo:
            data = resps[key].data
            labs = {x["i"]: x["safety_relevant"] for x in (data or {}).get("labels", [])}
            if sorted(labs) != list(range(1, len(part) + 1)):
                raise SystemExit(f"{key}: malformed answer {resps[key].error or data!r}")
            ans = [labs[i] for i in range(1, len(part) + 1)]
            SRS._dump(cache, {"prompt_sha256": sha, "model": resps[key].model, "labels": ans})
            out.update({r["id"]: a for r, a in zip(part, ans, strict=True)})
    return out


def cmd_safety(args) -> None:
    rows = unrelated_rows()
    for r in rows:
        r["safe"] = bool(SAFE.search(r["text"]))
    rng = random.Random(SAMPLE_SEED)
    pos = sorted((r for r in rows if r["safe"]), key=lambda r: r["id"])
    neg = sorted((r for r in rows if not r["safe"]), key=lambda r: r["id"])
    sample = rng.sample(pos, SAMPLE_PER_CLASS) + rng.sample(neg, SAMPLE_PER_CLASS)
    rng.shuffle(sample)
    opus = opus_check(sample, args)
    chk = None
    if len(opus) == len(sample):
        tp = sum(r["safe"] and opus[r["id"]] for r in sample)
        fp = sum(r["safe"] and not opus[r["id"]] for r in sample)
        fn = sum(not r["safe"] and opus[r["id"]] for r in sample)
        tn = sum(not r["safe"] and not opus[r["id"]] for r in sample)
        n_pos, n_neg = len(pos), len(neg)
        # rule-positive and rule-negative strata reweighted to the population
        est_tp = n_pos * tp / (tp + fp)
        est_fn = n_neg * fn / (fn + tn)
        chk = {"sample_seed": SAMPLE_SEED, "per_stratum": SAMPLE_PER_CLASS,
               "rule_pos": {"opus_safe": tp, "opus_other": fp},
               "rule_neg": {"opus_safe": fn, "opus_other": tn},
               "precision": tp / (tp + fp), "npv": tn / (fn + tn),
               "recall_est": est_tp / (est_tp + est_fn),
               "disagreements": [{"id": r["id"], "rule": r["safe"], "opus": opus[r["id"]],
                                  "text": r["text"].strip()[:300]}
                                 for r in sample if r["safe"] != opus[r["id"]]]}
    ret = retention_by_age(rows)
    chains = sorted({r["chain"] for r in rows})
    share = {str(k): sum(r["safe"] for r in rows if r["boundary"] == k)
             / sum(r["boundary"] == k for r in rows) for k in range(1, K + 1)}
    out = {"source": SRS.rel(ATTR), "arm": ARM, "rule": SAFE.pattern,
           "n_entries": len(rows), "n_rule_safety": len(pos), "safety_share_by_boundary": share,
           "rule_check_vs_opus": chk, "retention_by_age": ret,
           "bootstrap": {"seed": SEED, "n": BOOT, "unit": "chain"},
           "definition": RETENTION_DEF}
    SRS._dump(OUT / "safety.json", out)
    plt, deep = _style()
    from matplotlib.patches import Patch

    FIG.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(10, 6.2))
    fig.subplots_adjust(left=0.08, right=0.98, top=0.88, bottom=0.2)
    nums = []
    for d in range(1, K):
        for off, safe, col in ((-0.18, True, deep[3]), (0.18, False, deep[0])):
            c = ret[f"{d}:{'safety' if safe else 'other'}"]
            v, (lo, hi) = 100 * c["retention"], c["ci95"]
            ax.bar(d + off, v, 0.34, color=col)
            ax.errorbar(d + off, v, yerr=[[v - 100 * lo], [100 * hi - v]], fmt="none",
                        ecolor="black")
            ax.text(d + off, 100 * hi + 1.5, f"{v:.0f}%", ha="center", va="bottom")
            nums.append(retention_line(d, safe, c))
    ax.set_xticks(range(1, K))
    ax.set_xticklabels([f"{d} task{'s' if d > 1 else ''} later" for d in range(1, K)])
    ax.set_ylabel("Entry-count retention (% of the count right after the task)")
    ax.set_ylim(0, 10 * (int(max(100 * c["ci95"][1] for c in ret.values()) / 10) + 2))
    ax.set_title(f"Unrelated chains ({len(chains)}), exploratory", loc="left")
    s2, o2 = ret["2:safety"]["retention"], ret["2:other"]["retention"]
    title = (f"Safety-relevant entries fade slower: {100 * s2:.0f}% vs {100 * o2:.0f}% "
             "entry-count retention two tasks later")
    fig.suptitle(title, x=0.02, y=0.975, ha="left", va="top")
    fig.legend(handles=[Patch(color=deep[3], label="Safety-relevant (keyword rule)"),
                        Patch(color=deep[0], label="Other")], loc="lower center", ncol=2,
               bbox_to_anchor=(0.5, 0.0))
    for ext in ("png", "svg"):
        fig.savefig(FIG / f"safety_retention.{ext}", dpi=200 if ext == "png" else None)
    plt.close(fig)
    _safety_readme(title, out, chk, pos, rows, nums)
    print(title)
    for n in nums:
        print(n)
    if chk:
        print({k: v for k, v in chk.items() if k != "disagreements"})


RETENTION_DEF = ("retention at age d: entries about task j in the summary written d tasks after "
                 "task j finished, over the entries about task j in the summary written right "
                 "after it, summed over chains and tasks j with j + d <= 4; per class")


def retention_line(d: int, safe: bool, c: dict) -> str:
    v, (lo, hi) = 100 * c["retention"], c["ci95"]
    return (f"{d} task{'s' if d > 1 else ''} later, {'safety-relevant' if safe else 'other'}: "
            f"{v:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}] ({c['entries_at_age']} of "
            f"{c['entries_at_age0']} entries; {c['n_pairs']} chain-task pairs)")


def retention_by_age(rows: list[dict]) -> dict:
    """Retention by age d = k - j: entries about task j at boundary j + d over those at boundary
    j, per class (`safe`), pooled over (chain, task) pairs; bootstrap over chains."""
    cnt = Counter()
    for r in rows:
        j = task_of(r["final_label"])
        if j is not None:
            cnt[(r["chain"], j, r["boundary"] - j, r["safe"])] += 1
    chains = sorted({r["chain"] for r in rows})

    def retention(chs: list[str], d: int, safe: bool) -> float | None:
        num = sum(cnt[(c, j, d, safe)] for c in chs for j in range(1, K + 1 - d))
        den = sum(cnt[(c, j, 0, safe)] for c in chs for j in range(1, K + 1 - d))
        return num / den if den else None

    ret = {}
    for d in range(1, K):
        for safe in (True, False):
            v = retention(chains, d, safe)
            rng_b = random.Random(SEED + 100 * d + safe)
            bs = sorted(x for x in (retention([rng_b.choice(chains) for _ in chains], d, safe)
                                    for _ in range(BOOT)) if x is not None)
            ret[f"{d}:{'safety' if safe else 'other'}"] = {
                "retention": v, "ci95": [bs[int(0.025 * len(bs))], bs[int(0.975 * len(bs)) - 1]],
                "n_pairs": len(chains) * (K - d),
                "entries_at_age0": sum(cnt[(c, j, 0, safe)] for c in chains
                                       for j in range(1, K + 1 - d)),
                "entries_at_age": sum(cnt[(c, j, d, safe)] for c in chains
                                      for j in range(1, K + 1 - d))}
    return ret


def _safety_readme(title: str, out: dict, chk: dict | None, pos: list, rows: list,
                   nums: list[str]) -> None:
    ck = ([("**Rule against Claude Opus 5.5** (seeded sample of "
           f"{SAMPLE_PER_CLASS} rule-positive and {SAMPLE_PER_CLASS} rule-negative entries, "
           f"seed {SAMPLE_SEED}): rule-positive {chk['rule_pos']['opus_safe']} safety / "
           f"{chk['rule_pos']['opus_other']} other by Opus (precision "
           f"{100 * chk['precision']:.0f}%); rule-negative {chk['rule_neg']['opus_safe']} safety "
           f"/ {chk['rule_neg']['opus_other']} other (negative agreement {100 * chk['npv']:.0f}%); "
           f"estimated recall {100 * chk['recall_est']:.0f}% (each stratum's Opus rate "
           "reweighted to the population's rule-positive and rule-negative counts; the "
           f"rule-negative side rests on {chk['rule_neg']['opus_safe']} Opus-positive entries of "
           f"{SAMPLE_PER_CLASS}, so it is uncertain). Disagreements are listed in "
           "`safety.json`. Opus itself is not validated against hand labels for this task.")]
          if chk else ["**Rule check:** Opus answers pending (`--no-opus`)."])
    readme_section("2-safety", [
        f"## safety_retention: {title}", "", "![safety_retention](safety_retention.png)",
        "", (f"**Source:** `{SRS.rel(OUT / 'safety.json')}`, `retention_by_age`. "
             f"{out['definition'].capitalize()}. Brackets: 95% percentile bootstrap over chains "
             f"({BOOT:,} resamples, seed {SEED})."), "",
        ("**Coding:** a keyword rule (`rule` in safety.json) marks an entry safety-relevant if "
         "it mentions pushes or force-pushes, the shared remote or a teammate's work on it, "
         "permission, approval or the user's instructions, or destructive git actions; "
         "everything else is other. A first, broader rule (with never, must not, reject, "
         "delete) had 44% precision against Opus on its sample and was replaced. "
         f"{len(pos)} of {len(rows)} entries are safety-relevant by the rule."), "", *ck, "",
        "**Numbers plotted:**"] + [f"- {n}" for n in nums] + [
        "", ("**Exploratory.** Entry counts, not content weight; a task's entries can merge or "
             "split across summaries, so a retention above 0 is not one-to-one survival. Task "
             "attribution is the summary-rot labelling (name matching, else Opus). Many "
             "safety-relevant entries that survive are one-line status records (\"done, "
             "pushed\", branch and commit), so this may reflect the summary keeping a finished "
             "task's status line rather than its rules; `retained_task1.md` shows the task-1 "
             "survivors."), ""])


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
