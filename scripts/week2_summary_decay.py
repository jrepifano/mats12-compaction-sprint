def task_cells(per: list[dict]) -> dict:
    """Per boundary k: each task j's share of the summary (chain mean, bootstrap over chains)
    and the no-one-task share, from per-summary `shares` (summary_rot's categories)."""
    cells = {}
    for k in range(1, K + 1):
        ps = [p for p in per if p["boundary"] == k and p["shares"]["earlier"] is not None]
        cell = {"n_chains": len(ps)}
        for j in range(1, k + 1):
            cat = "current" if j == k else f"back_{k - j}"
            v = [p["shares"][cat] for p in ps]
            lo, hi = boot_ci(v, SEED + 10 * k + j)
            cell[f"task_{j}"] = {"mean": sum(v) / len(v), "ci95": [lo, hi],
                                 "by_chain": {p["chain"]: p["shares"][cat] for p in ps}}
        g = [p["shares"]["generic"] for p in ps]
        cell["generic"] = {"mean": sum(g) / len(g)}
        cells[str(k)] = cell
    return cells


def task_colors(deep: list[str]) -> dict[str, str]:
    return {f"task_{j}": deep[j - 1] for j in range(1, K + 1)} | {"generic": deep[7]}


def by_task_panel(ax, cells: dict, colors: dict) -> list[str]:
    """Stacked bars of task_cells, one per boundary, task 1's interval beside; numbers plotted."""
    nums = []
    for i, k in enumerate(range(1, K + 1)):
        c, bottom = cells[str(k)], 0.0
        for key in [f"task_{j}" for j in range(1, k + 1)] + ["generic"]:
            v = 100 * c[key]["mean"]
            ax.bar(i, v, 0.62, bottom=bottom, color=colors[key])
            if v >= 4:
                ax.text(i, bottom + v / 2, f"{v:.0f}%", ha="center", va="center")
            bottom += v
        t1 = c["task_1"]
        if c["n_chains"] > 1 and k > 1:  # task 1's share with its interval
            m, (lo, hi) = 100 * t1["mean"], t1["ci95"]
            ax.errorbar(i + 0.36, m, yerr=[[m - 100 * lo], [100 * hi - m]], fmt="o",
                        color="black")
        nums.append(f"After task {k} (n = {c['n_chains']} chains): " + "; ".join(
            f"task {j} {100 * c[f'task_{j}']['mean']:.1f}% "
            f"[{100 * c[f'task_{j}']['ci95'][0]:.1f}, {100 * c[f'task_{j}']['ci95'][1]:.1f}]"
            for j in range(1, k + 1)) + f"; no one task {100 * c['generic']['mean']:.1f}%")
    ax.set_xticks(range(K))
    ax.set_xticklabels([f"After task {k}" for k in range(1, K + 1)])
    ax.set_ylim(0, 100)
    return nums


def cmd_by_task(args) -> None:
    sh = json.loads(SHARES.read_text())
    per = [p for p in sh["per_summary"] if p["arm"] == ARM and p["kind"] == "boundary"]
    chains = sorted({p["chain"] for p in per})
    cells = task_cells(per)
    rows = unrelated_rows()
    kept = defaultdict(list)
    for r in rows:
        if r["boundary"] == K and r["final_label"] == "task_1":
            kept[r["chain"]].append(r)
    out = {"source": [SRS.rel(SHARES), SRS.rel(ATTR)], "arm": ARM, "chains": chains,
           "bootstrap": {"seed": SEED, "n": BOOT, "unit": "chain"}, "cells": cells,
           "task1_at_boundary4": {c: len(kept.get(c, [])) for c in chains}}
    SRS._dump(OUT / "by_task.json", out)
    t1 = [100 * cells[str(k)]["task_1"]["mean"] for k in range(1, K + 1)]
    title = ("Task 1 fades from the summary: " + " → ".join(f"{v:.0f}%" for v in t1)
             + f" of entries after tasks 1–{K}")
    plt, deep = _style()
    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch

    FIG.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(10, 6.2))
    fig.subplots_adjust(left=0.08, right=0.98, top=0.88, bottom=0.2)
    colors = task_colors(deep)
    nums = by_task_panel(ax, cells, colors)
    ax.set_ylabel("Share of summary entries (%)")
    ax.set_title(f"Five unrelated projects, compacted between tasks ({len(chains)} chains)",
                 loc="left")
    fig.suptitle(title, x=0.02, y=0.975, ha="left", va="top")
    handles = [Patch(color=colors[f"task_{j}"], label=f"Task {j}") for j in range(1, K + 1)]
    handles.append(Patch(color=colors["generic"], label="No one task"))
    handles.append(Line2D([], [], marker="o", color="black", label="Task 1 (95% CI)"))
    fig.legend(handles=handles, loc="lower center", ncol=6, bbox_to_anchor=(0.5, 0.0))
    for ext in ("png", "svg"):
        fig.savefig(FIG / f"summary_by_task.{ext}", dpi=200 if ext == "png" else None)
    plt.close(fig)
    md = ["# What the summary keeps from task 1 after task 4 (unrelated chains)", "",
          (f"Every entry of each chain's boundary-4 summary labelled task 1 (`{SRS.rel(ATTR)}`, "
           "`final_label`: name matching, else Claude Opus 5.5), quoted as written. "
           "Exploratory."), ""]
    for c in chains:
        rs = sorted(kept.get(c, []), key=lambda r: r["entry"])
        n4 = sum(r["boundary"] == K and r["chain"] == c for r in rows)
        md += [f"## {c}: {len(rs)} of {n4} entries", ""]
        md += [f"- ({r['decided_by']}) {r['text'].strip()}" for r in rs] or ["- (none)"]
        md.append("")
    (OUT / "retained_task1.md").write_text("\n".join(md))
    readme_section("1-by-task", [
        f"## summary_by_task: {title}", "", "![summary_by_task](summary_by_task.png)", "",
        (f"**Source:** `{SRS.rel(OUT / 'by_task.json')}` (`cells.<k>.task_<j>.mean`), from "
         f"`{SRS.rel(SHARES)}` `per_summary[]` (arm unrelated, kind boundary): task j's share at "
         "boundary k is the summary's `back_<k-j>` share (`current` when j = k). Chain means; "
         f"brackets are 95% percentile bootstrap intervals over chains ({BOOT:,} resamples, "
         f"seed {SEED})."), "", "**Numbers plotted:**"] + [f"- {n}" for n in nums] + [
        "", (f"**Task 1 entries after task 4:** {sum(len(v) for v in kept.values())} across "
             f"{sum(bool(v) for v in kept.values())} of {len(chains)} chains, quoted per chain "
             "in `retained_task1.md`."), ""])
    print(title)
    for n in nums:
        print(n)


