"""Week 2, experiment 4 ("chain stress"): the summary-rot data read by task instead of tasks-back
(J call, 29 Oct: does task 1 fade from the summary, a "vanishing summary"?). Exploratory, $0.

Reads the committed attribution (results/sprint/week2/chain_stress/summary_rot/attributions.jsonl
and shares.json, from scripts/week2_summary_rot.py); boundary summaries of the unrelated chains.

Subcommands (outputs under results/sprint/week2/chain_stress/summary_rot/decay/):
- `by-task`: each task's share of the summary at each boundary (task j at boundary k is the
  "k-j back" category), chain means with a seeded percentile bootstrap over chains ->
  by_task.json; figures/summary_by_task.{png,svg}; retained_task1.md (every boundary-4 entry
  labelled task 1, quoted, per chain).
- `safety [--no-opus]`: codes every entry safety-relevant or other with a keyword rule (pushes,
  force-pushes, rejections, permission or authorization, user rules and constraints, destructive
  actions), checks the rule against Claude Opus 5.5 on a seeded sample stratified by the rule
  (2 Max calls of 50 entries, cached under data/raw/sprint/s2/summary_rot/safety_opus/), then the
  retention of each class by age (boundaries since the task finished) -> safety.json,
  figures/safety_retention.{png,svg}.

    uv run python scripts/week2_summary_decay.py by-task
    uv run python scripts/week2_summary_decay.py safety

Figures follow AGENTS.md "Figures": seaborn defaults, no captions in the image; the notes are in
decay/figures/README.md, written by both subcommands.
"""

